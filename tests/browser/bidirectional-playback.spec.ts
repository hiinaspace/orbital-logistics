import {test,expect,type Page} from '@playwright/test';
import {setRate} from './playback-controls';
const state=async(page:Page)=>JSON.parse(await page.locator('#state-json').textContent()??'{}');
const ready=async(page:Page,id:string)=>expect.poll(async()=>{const s=await state(page);return s.ready&&s.set===id;},{timeout:45000}).toBe(true);
const pause=async(page:Page)=>{if((await state(page)).playing)await page.getByRole('button',{name:'Pause',exact:true}).click();};
const seek=async(page:Page,t:number)=>{await page.getByLabel('Simulation time').fill(String(t));await expect.poll(async()=>(await state(page)).t).toBe(t);};
test('finite scenes reverse physical samples, pause at zero, resume and stop at the beginning',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await ready(page,'orison-freight');await pause(page);await seek(page,8);
 const atEight=await state(page);
 await setRate(page,-2);expect((await state(page)).playing).toBe(false);
 await page.getByRole('button',{name:'Play',exact:true}).click();
 await expect.poll(async()=>(await state(page)).t).toBeLessThan(7.8);
 const control=(await page.getByLabel('Playback speed').boundingBox())!;
 await page.mouse.click(control.x+control.width/2,control.y+control.height/2);
 const held=await state(page);expect(held.playbackRate).toBe(0);expect(held.playing).toBe(false);
 await expect(page.locator('#speed-value')).toHaveText('0×');await page.waitForTimeout(250);expect((await state(page)).t).toBe(held.t);
 await setRate(page,2);expect((await state(page)).playing).toBe(true);
 await expect.poll(async()=>(await state(page)).t).toBeGreaterThan(held.t+.1);await pause(page);
 await seek(page,8);expect((await state(page)).ships.map((s:any)=>s.y)).toEqual(atEight.ships.map((s:any)=>s.y));expect((await state(page)).stocks).toEqual(atEight.stocks);
 await seek(page,.05);await setRate(page,-16);await page.getByRole('button',{name:'Play',exact:true}).click();
 await expect.poll(async()=>(await state(page)).t).toBe(0);expect((await state(page)).playing).toBe(false);
 await page.getByLabel('Replay',{exact:true}).check();await page.getByRole('button',{name:'Play',exact:true}).click();
 await expect.poll(async()=>(await state(page)).t).toBeGreaterThan(50);await pause(page);
 await setRate(page,0);await page.getByRole('button',{name:'Play',exact:true}).click();expect((await state(page)).playbackRate).toBe(-16);await pause(page);
 expect(errors).toEqual([]);
});
test('continuous reverse holds the published head, clamps to retained history and Live resumes forward',async({page})=>{
 test.setTimeout(120000);const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await ready(page,'orison-freight');await pause(page);
 await page.getByLabel('Model set').selectOption('orison-service');await ready(page,'orison-service');
 await setRate(page,16);if(!(await state(page)).playing)await page.getByRole('button',{name:'Play',exact:true}).click();
 await expect.poll(async()=>(await state(page)).t,{timeout:30000}).toBeGreaterThan(6);
 await setRate(page,-4);await expect.poll(async()=>(await state(page)).traffic.live).toBe(false);
 const reverse=await state(page);await expect.poll(async()=>(await state(page)).t).toBeLessThan(reverse.t-.2);
 await expect.poll(async()=>(await state(page)).traffic.pending).toBe(false);
 const head=(await state(page)).traffic.frontier;await page.waitForTimeout(250);expect((await state(page)).traffic.frontier).toBe(head);
 await setRate(page,0);const held=await state(page);await page.waitForTimeout(250);expect((await state(page)).t).toBe(held.t);
 await setRate(page,-16);await expect.poll(async()=>(await state(page)).t).toBe((await state(page)).traffic.oldest);
 expect((await state(page)).playing).toBe(false);expect((await state(page)).traffic.frontier).toBe(head);
 await page.getByRole('button',{name:'Return to live',exact:true}).click();
 expect((await state(page)).playbackRate).toBe(16);await expect.poll(async()=>(await state(page)).traffic.frontier).toBeGreaterThan(head);await pause(page);
 await page.getByLabel('Model set').selectOption('orison-relay-network');await ready(page,'orison-relay-network');await pause(page);
 await setRate(page,-16);expect((await state(page)).playbackRate).toBe(-2);
 await setRate(page,0);await page.getByLabel('Model set').selectOption('orison-service');await ready(page,'orison-service');await pause(page);await setRate(page,16);
 await page.getByLabel('Model set').selectOption('orison-relay-network');await ready(page,'orison-relay-network');
 expect((await state(page)).playing).toBe(false);await page.getByRole('button',{name:'Play',exact:true}).click();expect((await state(page)).playbackRate).toBe(-2);
 await page.getByRole('button',{name:'Return to live',exact:true}).click();expect((await state(page)).playbackRate).toBe(2);await pause(page);
 expect(errors).toEqual([]);
});
